create or replace function private.points_balance(p_user uuid) returns int
language sql stable security definer set search_path = '' as $$
  select coalesce(sum(amount), 0)::int from public.points_transactions where user_id = p_user and status = 'available'
$$;

-- ---------- منع الحذف المتتالي على السجلات المالية والتشغيلية ----------
do $$ declare r record; v_def text; begin
  for r in
    select c.conname, c.conrelid::regclass as tbl, pg_get_constraintdef(c.oid) as def
    from pg_constraint c
    where c.contype = 'f' and c.confdeltype = 'c'
      and c.conrelid in ('public.delivery_codes'::regclass, 'public.order_price_components'::regclass,
                         'public.order_status_history'::regclass)
  loop
    v_def := replace(r.def, 'ON DELETE CASCADE', 'ON DELETE RESTRICT');
    execute format('alter table %s drop constraint %I', r.tbl, r.conname);
    execute format('alter table %s add constraint %I %s', r.tbl, r.conname, v_def);
  end loop;
end $$;

