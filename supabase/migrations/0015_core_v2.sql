-- التحقق الثنائي: إلزامي للإدارة عند تفعيل admin_mfa_required، وإلا مطلوب فقط لمن فعّله
create or replace function private.mfa_ok() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce((auth.jwt()->>'aal') = 'aal2', false)
      or (not coalesce((select value = 'true'::jsonb from public.app_settings where key = 'admin_mfa_required'), false)
          and not exists (select 1 from auth.mfa_factors f where f.user_id = auth.uid() and f.status = 'verified'))
$$;

-- الموظفون الإداريون فقط (المندوب وموظف المركز ليسوا إدارة)
create or replace function private.is_staff() returns boolean
language sql stable security definer set search_path = '' as $$
  select private.is_active_user() and private.mfa_ok() and exists (
    select 1 from public.user_roles ur where ur.user_id = auth.uid()
      and ur.role in ('super_admin','admin','operations','finance','support'))
$$;

create or replace function private.is_courier() returns boolean
language sql stable security definer set search_path = '' as $$
  select private.is_active_user() and exists (
    select 1 from public.user_roles ur where ur.user_id = auth.uid() and ur.role = 'courier')
$$;

create or replace function private.is_hub() returns boolean
language sql stable security definer set search_path = '' as $$
  select (private.is_active_user() and exists (
    select 1 from public.user_roles ur where ur.user_id = auth.uid() and ur.role = 'hub'))
    or private.is_admin() or (private.has_role('operations') and private.mfa_ok())
$$;

create or replace function private.is_finance() returns boolean
language sql stable security definer set search_path = '' as $$
  select private.is_admin() or (private.has_role('finance') and private.mfa_ok())
$$;
grant execute on function private.is_courier(), private.is_hub(), private.is_finance() to authenticated;

